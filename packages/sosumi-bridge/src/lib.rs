//! The FFI surface between the Flutter UI and the Rust core.
//!
//! This crate exists to keep the boundary small. The UI depends on this and
//! nothing else, so the generated bindings are the whole contract, and moving
//! logic across it is a deliberate act rather than an accident. See
//! `docs/adr/0002-rust-core-flutter-ui.md`.
//!
//! Two rules govern what appears here:
//!
//! 1. **Types are bridge-friendly.** Dart has no notion of a Rust trait object
//!    or a borrowed slice, so the public functions take and return owned data
//!    from [`api`].
//! 2. **The UI never sees a key or a URL.** Streams are referenced by id, and
//!    the audio path is driven from Rust.

#![deny(unsafe_code)]

pub mod api;
// The generated bindings are machine-written and use `unsafe` and `unwrap`
// internally for FFI plumbing. That is contained to this module; the rest of
// the crate still denies both. Regenerated by `flutter_rust_bridge_codegen`.
#[allow(unsafe_code)]
#[allow(clippy::all, clippy::pedantic, clippy::nursery, clippy::restriction)]
#[allow(unused, warnings)]
mod frb_generated;

pub use api::*;
